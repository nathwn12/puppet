//! Build-time provenance stamp + embedded skill files.
use std::fs;
use std::path::Path;
use std::process::Command;

fn git(args: &[&str]) -> Option<String> {
    let out = Command::new("git").args(args).output().ok()?;
    if !out.status.success() {
        return None;
    }
    Some(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

fn main() {
    let sha = git(&["rev-parse", "HEAD"])
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "unknown".to_string());
    let dirty = git(&["status", "--porcelain"]).is_some_and(|s| !s.is_empty());

    println!("cargo:rustc-env=PUPPET_GIT_SHA={sha}");
    println!(
        "cargo:rustc-env=PUPPET_GIT_DIRTY={}",
        if dirty { "-dirty" } else { "" }
    );

    println!("cargo:rerun-if-changed=.git/index");
    println!("cargo:rerun-if-changed=.git/HEAD");
    println!("cargo:rerun-if-changed=.git/refs/heads");
    println!("cargo:rerun-if-changed=.git/logs/HEAD");
    println!("cargo:rerun-if-changed=Cargo.toml");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src");
    println!("cargo:rerun-if-changed=tests");
    println!("cargo:rerun-if-changed=skills");

    // Collect skill files.
    let manifest = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    let skills_root = Path::new(&manifest).join("skills");
    let out_dir = std::env::var("OUT_DIR").unwrap();
    let out_path = Path::new(&out_dir).join("skills_generated.rs");

    let mut entries: Vec<(String, String)> = Vec::new(); // (uri, abs path)
    if skills_root.exists() {
        for entry in walkdir(&skills_root) {
            let rel = entry.strip_prefix(&skills_root).unwrap();
            let rel_str = rel.to_string_lossy().replace('\\', "/");
            let uri = format!("skill://{}", rel_str);
            entries.push((uri, entry.to_string_lossy().to_string()));
        }
    }
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    use sha2::{Digest, Sha256};
    let mut code = String::new();
    code.push_str("// auto-generated by build.rs; do not edit\n");
    code.push_str("pub struct EmbeddedSkillFile {\n");
    code.push_str("    pub uri: &'static str,\n");
    code.push_str("    pub bytes: &'static [u8],\n");
    code.push_str("    pub digest: &'static str,\n");
    code.push_str("    pub size: usize,\n");
    code.push_str("}\n");
    code.push_str("pub static SKILL_FILES: &[EmbeddedSkillFile] = &[\n");
    for (uri, abspath) in &entries {
        let bytes = fs::read(abspath).unwrap();
        let mut hasher = Sha256::new();
        hasher.update(&bytes);
        let hash = hasher.finalize();
        let hex: String = hash.iter().map(|b| format!("{:02x}", b)).collect();
        let digest = format!("sha256:{}", hex);
        code.push_str(&format!(
            "    EmbeddedSkillFile {{ uri: {:?}, bytes: include_bytes!({:?}), digest: {:?}, size: {} }},\n",
            uri, abspath, digest, bytes.len()
        ));
    }
    code.push_str("];\n");
    fs::write(&out_path, code).unwrap();
}

fn walkdir(root: &Path) -> Vec<std::path::PathBuf> {
    let mut out = Vec::new();
    fn rec(dir: &Path, out: &mut Vec<std::path::PathBuf>) {
        if let Ok(rd) = fs::read_dir(dir) {
            for e in rd.flatten() {
                let p = e.path();
                if p.is_dir() {
                    rec(&p, out);
                } else if p.is_file() {
                    out.push(p);
                }
            }
        }
    }
    rec(root, &mut out);
    out
}
